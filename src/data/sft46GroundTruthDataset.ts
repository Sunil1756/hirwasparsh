/**
 * Converts all 46 SFT Ground-Truth Pairs into standard Gemini / Vertex AI JSONL format.
 */
export function exportSftDatasetAsJsonl(pairs: SftGroundTruthPair[] = SFT_46_GROUND_TRUTH_DATASET): string {
  return pairs
    .map((p) =>
      JSON.stringify({
        id: p.id,
        source: p.sourceDocument,
        page: p.sourcePageNumber,
        verdict: p.groundTruthVerdict,
        contents: [
          {
            role: "user",
            parts: [
              {
                text: `${p.prompt}\nVisual Context: ${p.visualEvidenceDescription}\nTarget Species Context: Indigenous Native Agroforestry`,
              },
            ],
          },
          {
            role: "model",
            parts: [
              {
                text: JSON.stringify(p.completion, null, 2),
              },
            ],
          },
        ],
      })
    )
    .join("\n");
}
